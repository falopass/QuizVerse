/**
 * Datos del filtro de apodos.
 *
 * Todo se compara sobre el apodo "plegado": minúsculas, sin tildes, con el
 * leetspeak ya decodificado y sin separadores. Por eso las listas van siempre
 * en minúscula, sin tildes y sin dígitos leet ("puta", no "put4").
 *
 * Tipos de coincidencia (`match`):
 * - 'contains' (default): el término como subcadena del apodo plegado. Atrapa
 *   la palabra dentro de otra ("xxputaxx") y la escrita con separadores
 *   ("p.u.t.a" pliega a "puta"). Los falsos positivos se gobiernan con
 *   EXCEPTION_WORDS.
 * - 'exact': el token (o el apodo entero plegado) ES el término. Para palabras
 *   que son insulto solas pero subcadenas de palabras normales: "anal" (Analía,
 *   canal), "sex" (Essex), "ass" (class), "coger" (escoger), "cono" (conocer).
 * - 'boundary': subcadena que solo cuenta si no va precedida de una vocal de
 *   `allowPrev`. Para "culo"/"culi", que son término propio y a la vez sufijo
 *   de cientos de palabras legítimas (-ículo/-áculo/-éculo: artículo, oráculo,
 *   película; peculiar, oculista). "Lameculo" y "su culo" se cubren con términos
 *   'contains' explícitos.
 *
 * Qué NO se lista a propósito (documentado para quien mantenga esto):
 * - Identidades: gay, lesbiana, trans, indio, gitano, gringo. Un apodo que
 *   afirma una identidad no es moderable; los slurs sí (maricón, faggot…).
 * - Palabras ambiguas de uso masivo: concha (nombre propio y marca), pico,
 *   poto, raja, hueco, bicho ("El Bicho"), pingo, minga, chichi, cuca, papaya,
 *   almeja, mono, indio, negro. Bloquearlas haría más daño que bien: el
 *   apodo ofensivo se reporta, no se adivina.
 * - Figuras públicas/políticos (putin, trump…): no son grosería; "putin" entra
 *   en EXCEPTION_WORDS porque el stem "puti" sí se bloquea.
 */

export type BlockedMatch = 'contains' | 'exact' | 'boundary';

export interface BlockedTerm {
  /** Forma plegada a buscar (minúsculas, sin tildes). */
  term: string;
  match?: BlockedMatch;
  /** En 'boundary': vocales que legitimizan el prefijo (p. ej. -ículo). */
  allowBefore?: string;
}

