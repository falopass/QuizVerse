#!/usr/bin/env node
/**
 * Emits the editorial seed (scripts/seed/editorial-seed.json) as idempotent SQL.
 *
 * The seed fills the categories the imported catalogue left empty — history,
 * geography and sports — with quizzes whose answers are stable, checkable facts.
 *
 *   node scripts/seed/emit-editorial-seed.mjs              # print SQL to stdout
 *   node scripts/seed/emit-editorial-seed.mjs --write       # write the .sql file
 *
 * The script validates before emitting: unique slugs, exactly one correct option
 * per trivia question, 2–10 options per question, and a category that exists in
 * the catalogue. A seed that fails validation never reaches the database.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SEED_PATH = join(ROOT, 'scripts', 'seed', 'editorial-seed.json');
const OUTPUT_DIR = join(ROOT, 'generated', 'audit');
const OUTPUT_PATH = join(OUTPUT_DIR, 'editorial-seed.sql');

const CATEGORIES = new Set([
  'personality',
  'movies-tv',
  'culture',
  'music',
  'lifestyle',
  'gaming',
  'science',
  'history',
  'sports',
  'geography',
  'anime-manga',
  'food-drink',
  'literature',
  'technology',
  'pop-culture',
  'animals',
  'relationships',
]);

const LANGUAGES = new Set(['en', 'es']);

/** Fails the build instead of silently importing a broken quiz. */
function validate(quizzes) {
  const errors = [];
  const seenSlugs = new Set();

  quizzes.forEach((quiz, index) => {
    const where = `quiz[${index}] ${quiz.slug ?? '(no slug)'}`;

    if (!quiz.slug || !/^[a-z0-9-]+$/.test(quiz.slug)) errors.push(`${where}: invalid slug`);
    if (seenSlugs.has(quiz.slug)) errors.push(`${where}: duplicate slug`);
    seenSlugs.add(quiz.slug);

    if (!quiz.title || quiz.title.length < 10) errors.push(`${where}: title too short`);
    if (!quiz.description || quiz.description.length < 40) {
      errors.push(`${where}: description too short`);
    }
    if (!CATEGORIES.has(quiz.category)) errors.push(`${where}: unknown category`);
    if (!LANGUAGES.has(quiz.language)) errors.push(`${where}: unknown language`);
    if (!quiz.slug.startsWith(`${quiz.language}-`)) {
      errors.push(`${where}: slug must start with the language prefix`);
    }
    if (!Array.isArray(quiz.questions) || quiz.questions.length < 5) {
      errors.push(`${where}: needs at least 5 questions`);
    }

    (quiz.questions ?? []).forEach((question, questionIndex) => {
      const questionWhere = `${where} q${questionIndex + 1}`;
      if (!question.question) errors.push(`${questionWhere}: missing text`);
      if (!Array.isArray(question.options) || question.options.length < 2) {
        errors.push(`${questionWhere}: needs at least 2 options`);
      }
      const correct = (question.options ?? []).filter((option) => option.is_correct === true);
      if (quiz.quiz_type === 'trivia' && correct.length !== 1) {
        errors.push(`${questionWhere}: trivia needs exactly one correct option`);
      }
      const optionIds = new Set((question.options ?? []).map((option) => option.id));
      if (optionIds.size !== (question.options ?? []).length) {
        errors.push(`${questionWhere}: duplicate option ids`);
      }
    });
  });

  return errors;
}

function escapeSqlLiteral(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function buildSql(quizzes) {
  const statements = [
    '-- Editorial seed generated by scripts/seed/emit-editorial-seed.mjs',
    '-- Idempotent: re-running inserts nothing new (ON CONFLICT (slug) DO NOTHING).',
    '-- Apply:',
    '--   docker exec -i supabase-db psql -U postgres -d postgres < editorial-seed.sql',
    'begin;',
  ];

  for (const quiz of quizzes) {
    const tags = `array[${quiz.tags.map(escapeSqlLiteral).join(', ')}]::text[]`;
    statements.push(
      [
        'insert into public.quizzes',
        // `question_count` is a generated column (jsonb_array_length(questions)).
        '  (slug, title, description, quiz_type, difficulty, language, category_id,',
        '   questions, results, tags, estimated_minutes, status,',
        '   is_featured, is_ai_generated, published_at)',
        'values (',
        `  ${escapeSqlLiteral(quiz.slug)},`,
        `  ${escapeSqlLiteral(quiz.title)},`,
        `  ${escapeSqlLiteral(quiz.description)},`,
        `  ${escapeSqlLiteral(quiz.quiz_type)},`,
        `  ${escapeSqlLiteral(quiz.difficulty)},`,
        `  ${escapeSqlLiteral(quiz.language)},`,
        `  (select id from public.categories where slug = ${escapeSqlLiteral(quiz.category)}),`,
        `  ${escapeSqlLiteral(JSON.stringify(quiz.questions))}::jsonb,`,
        '  null,',
        `  ${tags},`,
        `  ${Number(quiz.estimated_minutes) || 3},`,
        "  'published',",
        '  false,',
        '  false,',
        '  now()',
        ')',
        'on conflict (slug) do nothing;',
      ].join('\n')
    );
  }

  statements.push('-- categories.quiz_count is maintained by the trigger on quizzes.', 'commit;');

  return `${statements.join('\n\n')}\n`;
}

function main() {
  const write = process.argv.includes('--write');
  const seed = JSON.parse(readFileSync(SEED_PATH, 'utf8'));
  const quizzes = seed.quizzes ?? [];

  const errors = validate(quizzes);
  if (errors.length > 0) {
    console.error(`Seed validation failed (${errors.length}):`);
    for (const error of errors) console.error(`  - ${error}`);
    process.exit(1);
  }

  const sql = buildSql(quizzes);
  if (write) {
    mkdirSync(OUTPUT_DIR, { recursive: true });
    writeFileSync(OUTPUT_PATH, sql, 'utf8');
    console.log(`Wrote ${OUTPUT_PATH} (${quizzes.length} quizzes)`);
  } else {
    process.stdout.write(sql);
  }

  const byCategory = quizzes.reduce((accumulator, quiz) => {
    accumulator[quiz.category] = (accumulator[quiz.category] ?? 0) + 1;
    return accumulator;
  }, {});
  console.log('Validated:', JSON.stringify(byCategory));
}

main();
